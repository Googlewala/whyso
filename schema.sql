CREATE TABLE IF NOT EXISTS users (id TEXT PRIMARY KEY, email TEXT, created INTEGER, plan_until INTEGER DEFAULT 0);
CREATE INDEX IF NOT EXISTS users_email ON users(email);
CREATE TABLE IF NOT EXISTS blobs (uid TEXT, k TEXT, v TEXT, updated INTEGER, PRIMARY KEY (uid, k));
CREATE TABLE IF NOT EXISTS events (id TEXT PRIMARY KEY, created INTEGER);
CREATE TABLE IF NOT EXISTS payments (id TEXT PRIMARY KEY, email TEXT, amount INTEGER, used INTEGER DEFAULT 0, created INTEGER);
